export function t(key, params = {}) {
  const v = MESSAGES[key]
  if (v === undefined) return `[${key}]`
  return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`))
}

const ERROR_KEYS = { USER_NOT_REGISTERED: 'Exception12' }

export function errorCode(err) {
  const code = err?.response?.data?.code
  if (code) return code
  if (err?.code === 'ECONNABORTED') return 'TIMEOUT'
  if (err?.response) return 'UNKNOWN'
  if (err?.request) return 'NETWORK'
  return 'UNKNOWN'
}

export function errorMessage(err) {
  const code = errorCode(err)
  return t(ERROR_KEYS[code] ?? `SEW_ERR_${code}`)
}

// 칸 오류 문구(칸 검사 결과 { code, params } — 패널 칸 옆·적용 줄·표 갈 곳 칸). 문구는 RULE_<code> 이고, 미해결 갈 곳은
// 칸 앞에서 할 일만 짧게 — 원래 번호를 알면 함께 보인다(목업 validate "갈 곳을 고르세요(원래 N번)."). 저장 창 목록은 RULE_ 문구 그대로.
export function fieldMessage(e) {
  const params = e?.params || {}
  if (e?.code === 'NEXT_UNRESOLVED') return t(params.value === undefined || params.value === null ? 'SEW_EDIT_PICK_UNRESOLVED' : 'SEW_EDIT_PICK_UNRESOLVED_FROM', params)
  return t(`RULE_${e?.code}`, params)
}

// 경고·알림 문구. params.field 가 있으면 그 field 의 문구(예: SEW_NOTE_PARSE_FAILED_bi)를 먼저 찾고, 없으면 코드 공통 문구.
// 편집 중 실시간 알림(칸 검사 code, 예: NEXT_UNRESOLVED·ACCEPT_TOO_LOW)은 SEW_NOTE_ 문구가 없으면 칸 문구 RULE_<code> 를 쓴다.
export function noteMessage(note) {
  const params = note.params || {}
  const specific = typeof params.field === 'string' ? `SEW_NOTE_${note.code}_${params.field}` : null
  if (specific && MESSAGES[specific] !== undefined) return t(specific, params)
  const key = `SEW_NOTE_${note.code}`
  if (MESSAGES[key] === undefined && MESSAGES[`RULE_${note.code}`] !== undefined) return t(`RULE_${note.code}`, params)
  return t(key, params)
}
