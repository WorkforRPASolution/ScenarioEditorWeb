// 스냅샷 왼쪽 패널 — 설비 고르기·날짜·달력·거르기·상태 글 (P3 설계 §4.2)
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import { mount, flushPromises, enableAutoUnmount } from '@vue/test-utils'
import { setActivePinia, createPinia } from 'pinia'

const api = vi.hoisted(() => ({ equipment: vi.fn(), snapshotDays: vi.fn(), snapshots: vi.fn(), snapshotImage: vi.fn() }))
vi.mock('../api', async (importOriginal) => ({ ...(await importOriginal()), scenarioEditorApi: api }))
import SnapshotPanel from '../components/snapshot/SnapshotPanel.vue'
import { useSnapshotStore } from '../stores/snapshotStore'
import { MESSAGES, t } from '../messages'

enableAutoUnmount(afterEach)
const ok = (data) => Promise.resolve({ data: { data } })
const defer = () => { let resolve; const promise = new Promise((res) => { resolve = res }); return { promise, resolve } }
const fail = (status, code) => ({ response: { status, data: { code } } })
const eq = (eqpId, process, model) => ({ eqpId, process, model, line: 'L' })
const EQP = [eq('SEWT_PHOTO_A01', 'SEWPHOTO', 'SEWMODELA'), eq('SEWT_CVD_B01', 'SEWCVD', 'SEWMODELB'), eq('SEWT_CVD_A01', 'SEWCVD', 'SEWMODELA'), eq('SEWT_ETCH_A01', 'SEWETCH', 'SEWMODELA')]
const click = (n) => ({ fileName: `${n}_[1][2].png`, ms: n, time: '09:00:00', shift: 'DAY', kind: 'click', tag: null, x: 1, y: 2, txn: null, hasHistory: false, memo: null, daysLeft: 15 })
const tag = (n) => ({ fileName: `${n}_[9999][${n}].png`, ms: n, time: '10:00:00', shift: 'DAY', kind: 'tag', tag: 'start', x: null, y: null, txn: String(n), hasHistory: false, memo: null, daysLeft: 15 })
const ITEMS = [click(10), tag(11), click(12), tag(13), click(14)]
const DAYS = { latest: '2026-11-11', today: '2026-11-11', oldest: '2026-10-27', days: null, truncated: false }
const listOf = (eqpId, date, items = ITEMS, more = {}) => ({ eqpId, date, timeDiff: 0, items, skipped: 0, truncated: false, ...more })
const tid = (w, id) => w.find(`[data-testid="${id}"]`)
const tids = (w, id) => w.findAll(`[data-testid="${id}"]`)

describe('SnapshotPanel', () => {
  beforeEach(() => {
    setActivePinia(createPinia())
    localStorage.clear()
    Object.values(api).forEach((f) => f.mockReset())
    api.equipment.mockImplementation(() => ok({ items: EQP }))
    api.snapshotDays.mockImplementation((eqpId) => ok({ eqpId, ...DAYS }))
    api.snapshots.mockImplementation((eqpId, date) => ok(listOf(eqpId, date)))
    api.snapshotImage.mockImplementation(() => Promise.resolve({ data: new Blob(['x']) }))
    vi.spyOn(URL, 'createObjectURL').mockImplementation(() => 'blob:x')
    vi.spyOn(URL, 'revokeObjectURL').mockImplementation(() => {})
  })
  afterEach(() => vi.restoreAllMocks())

  const mountPanel = async ({ prefer = null, pick = null } = {}) => {
    const s = useSnapshotStore()
    await s.setOpen(true)
    if (pick) await s.pickEquipment(pick, { select: false })
    const w = mount(SnapshotPanel, { props: { prefer }, attachTo: document.body })
    await flushPromises()
    return { w, s }
  }
  const options = (w) => tids(w, 'se-snap-eqp-option').map((o) => o.attributes('data-eqp'))

  describe('설비 고르기', () => {
    it('설비를 고르기 전에는 "설비를 고르세요." 이고 날짜·거르기는 꺼져 있다', async () => {
      const { w } = await mountPanel()
      expect(tid(w, 'se-snap-state').text()).toBe(MESSAGES.SEW_SNAP_PICK_EQP)
      expect(tid(w, 'se-snap-date-prev').attributes('disabled')).toBeDefined()
      expect(tid(w, 'se-snap-date').attributes('disabled')).toBeDefined()
      expect(tid(w, 'se-snap-date-next').attributes('disabled')).toBeDefined()
      expect(tid(w, 'se-snap-list').exists()).toBe(false)
    })
    it('입력 칸에 들어가면 내 범위 설비가 ID 순으로 뜨고, 치면 맞는 것만 남는다', async () => {
      const { w } = await mountPanel()
      expect(options(w)).toEqual([])
      await tid(w, 'se-snap-eqp-input').trigger('focus')
      expect(options(w)).toEqual(['SEWT_CVD_A01', 'SEWT_CVD_B01', 'SEWT_ETCH_A01', 'SEWT_PHOTO_A01'])
      await tid(w, 'se-snap-eqp-input').setValue('photo')
      expect(options(w)).toEqual(['SEWT_PHOTO_A01'])
      await tid(w, 'se-snap-eqp-input').setValue('zzz')
      expect(options(w)).toEqual([])
      expect(w.text()).toContain(MESSAGES.SEW_SNAP_EQP_NONE)
    })
    it('공정을 고르면 모델 목록이 그 공정 것으로 줄고 설비도 좁혀진다', async () => {
      const { w } = await mountPanel()
      const models = () => tid(w, 'se-snap-eqp-model').findAll('option').map((o) => o.element.value)
      expect(tid(w, 'se-snap-eqp-process').findAll('option').map((o) => o.element.value)).toEqual(['', 'SEWCVD', 'SEWETCH', 'SEWPHOTO'])
      expect(models()).toEqual(['', 'SEWMODELA', 'SEWMODELB'])
      await tid(w, 'se-snap-eqp-model').setValue('SEWMODELB')
      await tid(w, 'se-snap-eqp-process').setValue('SEWETCH')
      expect(models()).toEqual(['', 'SEWMODELA'])
      expect(tid(w, 'se-snap-eqp-model').element.value).toBe('') // 그 공정에 없는 모델은 풀린다
      await tid(w, 'se-snap-eqp-input').trigger('focus')
      expect(options(w)).toEqual(['SEWT_ETCH_A01'])
    })
    it('설비를 누르면 그 설비를 고르고 목록이 닫히며 입력 칸에 설비 ID 가 남는다', async () => {
      const { w, s } = await mountPanel()
      await tid(w, 'se-snap-eqp-input').trigger('focus')
      await tids(w, 'se-snap-eqp-option').find((o) => o.attributes('data-eqp') === 'SEWT_CVD_B01').trigger('click')
      await flushPromises()
      expect(s.eqpId).toBe('SEWT_CVD_B01')
      expect(api.snapshotDays).toHaveBeenCalledWith('SEWT_CVD_B01')
      expect(options(w)).toEqual([])
      expect(tid(w, 'se-snap-eqp-input').element.value).toBe('SEWT_CVD_B01')
    })
    it('Enter 는 맞는 첫 설비를 고르고, Esc 는 목록을 닫고 입력을 지금 설비로 되돌린다', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      const input = tid(w, 'se-snap-eqp-input')
      await input.trigger('focus')
      await input.setValue('etch')
      await input.trigger('keydown', { key: 'Escape' })
      expect(options(w)).toEqual([])
      expect(input.element.value).toBe('SEWT_CVD_A01')
      await input.trigger('focus')
      await input.setValue('etch')
      await input.trigger('keydown', { key: 'Enter' })
      await flushPromises()
      expect(s.eqpId).toBe('SEWT_ETCH_A01')
    })
    it('설비를 눌러 고른 뒤(입력 칸이 초점을 지킨 채) 다시 누르거나 글자를 치면 목록이 다시 열린다', async () => {
      const { w, s } = await mountPanel()
      const input = tid(w, 'se-snap-eqp-input')
      await input.trigger('focus')
      await tids(w, 'se-snap-eqp-option').find((o) => o.attributes('data-eqp') === 'SEWT_CVD_B01').trigger('click')
      await flushPromises()
      expect(options(w)).toEqual([])
      await input.setValue('etch') // 초점은 그대로라 focus 이벤트가 다시 오지 않는다
      expect(options(w)).toEqual(['SEWT_ETCH_A01'])
      await input.trigger('keydown', { key: 'Escape' })
      expect(options(w)).toEqual([])
      await input.trigger('click')
      expect(options(w)).toHaveLength(4)
      expect(s.eqpId).toBe('SEWT_CVD_B01')
    })
    it('아무것도 치지 않고 Enter 를 누르면 설비를 바꾸지 않고 목록만 닫는다', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_PHOTO_A01' })
      const input = tid(w, 'se-snap-eqp-input')
      const calls = api.snapshotDays.mock.calls.length
      await input.trigger('focus')
      expect(options(w)[0]).toBe('SEWT_CVD_A01') // 전체 목록의 첫 설비는 다른 설비다
      await input.trigger('keydown', { key: 'Enter' })
      await flushPromises()
      expect(s.eqpId).toBe('SEWT_PHOTO_A01')
      expect(api.snapshotDays.mock.calls.length).toBe(calls)
      expect(options(w)).toEqual([])
    })
    it('이미 고른 설비가 입력 칸에 있을 때 들어가면 전체 목록을 보인다(그 ID 로 거르지 않는다)', async () => {
      const { w } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      expect(tid(w, 'se-snap-eqp-input').element.value).toBe('SEWT_CVD_A01')
      await tid(w, 'se-snap-eqp-input').trigger('focus')
      expect(options(w)).toHaveLength(4)
    })
    it('열린 시나리오의 공정·모델 설비가 먼저 온다', async () => {
      const { w } = await mountPanel({ prefer: { process: 'SEWPHOTO', model: 'SEWMODELA' } })
      await tid(w, 'se-snap-eqp-input').trigger('focus')
      expect(options(w)[0]).toBe('SEWT_PHOTO_A01')
    })
    it('맞는 설비가 50대를 넘으면 50대만 그리고 나머지 수를 알린다', async () => {
      api.equipment.mockImplementation(() => ok({ items: Array.from({ length: 73 }, (_, i) => eq(`E${String(i).padStart(3, '0')}`, 'P', 'M')) }))
      const { w } = await mountPanel()
      await tid(w, 'se-snap-eqp-input').trigger('focus')
      expect(options(w)).toHaveLength(50)
      expect(tid(w, 'se-snap-eqp-more').text()).toBe(t('SEW_SNAP_EQP_MORE', { n: 23 }))
    })
    it('설비 목록을 받지 못하면 문구와 [다시 시도], 볼 설비가 없으면 그 안내', async () => {
      api.equipment.mockImplementationOnce(() => Promise.reject(fail(503, 'UPSTREAM_DOWN')))
      const { w, s } = await mountPanel()
      expect(tid(w, 'se-snap-eqp-error').text()).toContain(MESSAGES.SEW_ERR_UPSTREAM_DOWN)
      api.equipment.mockImplementationOnce(() => ok({ items: [] }))
      await tid(w, 'se-snap-eqp-retry').trigger('click')
      await flushPromises()
      expect(s.equipment.status).toBe('ready')
      expect(tid(w, 'se-snap-eqp-error').exists()).toBe(false)
      expect(tid(w, 'se-snap-state').text()).toBe(MESSAGES.SEW_SNAP_EQP_EMPTY)
    })
  })

  describe('날짜·달력', () => {
    it('날짜와 요일을 보이고 ◀ ▶ 로 하루씩 — 보관 기간 끝에서는 꺼진다', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      expect(tid(w, 'se-snap-date').text()).toContain('2026-11-11 (수)')
      expect(tid(w, 'se-snap-date-next').attributes('disabled')).toBeDefined()
      await tid(w, 'se-snap-date-prev').trigger('click')
      await flushPromises()
      expect(s.date).toBe('2026-11-10')
      expect(tid(w, 'se-snap-date').text()).toContain('2026-11-10 (화)')
      expect(tid(w, 'se-snap-date-next').attributes('disabled')).toBeUndefined()
      await s.setDate('2026-10-27')
      await flushPromises()
      expect(tid(w, 'se-snap-date-prev').attributes('disabled')).toBeDefined()
    })
    it('날짜를 누르면 달력이 열리고 날짜별 개수를 받는다 — 있는 날에 점, 보관 기간 밖은 꺼짐', async () => {
      api.snapshotDays.mockImplementation((eqpId, counts) => ok({ eqpId, ...DAYS, days: counts ? { '2026-11-10': 3, '2026-11-11': 20 } : null }))
      const { w } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      expect(tid(w, 'se-snap-calendar').exists()).toBe(false)
      await tid(w, 'se-snap-date').trigger('click')
      await flushPromises()
      expect(api.snapshotDays).toHaveBeenLastCalledWith('SEWT_CVD_A01', true)
      const days = tids(w, 'se-snap-cal-day')
      expect(days).toHaveLength(21)
      const by = (date) => days.find((d) => d.attributes('data-date') === date)
      expect(by('2026-11-10').attributes('data-has')).toBe('1')
      expect(by('2026-11-10').attributes('title')).toBe(t('SEW_SNAP_CAL_COUNT', { n: 3 }))
      expect(by('2026-11-09').attributes('data-has')).toBeUndefined()
      expect(by('2026-10-25').attributes('disabled')).toBeDefined()
      expect(by('2026-11-12').attributes('disabled')).toBeDefined()
      expect(by('2026-11-11').attributes('aria-pressed')).toBe('true')
      expect(tid(w, 'se-snap-calendar').text()).toContain(t('SEW_SNAP_CAL_NOTE', { date: '2026-10-27' }))
    })
    it('달력에서 날을 누르면 그 날로 가고 달력이 닫힌다', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      await tid(w, 'se-snap-date').trigger('click')
      await flushPromises()
      await tids(w, 'se-snap-cal-day').find((d) => d.attributes('data-date') === '2026-11-03').trigger('click')
      await flushPromises()
      expect(s.date).toBe('2026-11-03')
      expect(tid(w, 'se-snap-calendar').exists()).toBe(false)
    })
    it('Esc·바깥 누름·날짜 다시 누름으로 닫힌다', async () => {
      const { w } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      const openCal = async () => { await tid(w, 'se-snap-date').trigger('click'); await flushPromises() }
      await openCal()
      document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' }))
      await flushPromises()
      expect(tid(w, 'se-snap-calendar').exists()).toBe(false)
      await openCal()
      document.body.dispatchEvent(new MouseEvent('mousedown', { bubbles: true }))
      await flushPromises()
      expect(tid(w, 'se-snap-calendar').exists()).toBe(false)
      await openCal()
      await tid(w, 'se-snap-calendar').trigger('mousedown') // 달력 안을 누르면 닫히지 않는다
      expect(tid(w, 'se-snap-calendar').exists()).toBe(true)
      await tid(w, 'se-snap-date').trigger('click')
      expect(tid(w, 'se-snap-calendar').exists()).toBe(false)
    })
    it('개수를 받는 중·받지 못함·많아서 잘림을 달력 안에 알린다 — 날짜는 그래도 고를 수 있다', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      const gate = defer()
      api.snapshotDays.mockImplementationOnce(() => gate.promise)
      await tid(w, 'se-snap-date').trigger('click')
      expect(tid(w, 'se-snap-calendar').text()).toContain(MESSAGES.SEW_SNAP_CAL_LOADING)
      gate.resolve({ data: { data: { eqpId: 'SEWT_CVD_A01', ...DAYS, days: { '2026-11-11': 5 }, truncated: true } } })
      await flushPromises()
      expect(tid(w, 'se-snap-calendar').text()).toContain(MESSAGES.SEW_SNAP_CAL_TRUNCATED)
      await tid(w, 'se-snap-date').trigger('click')
      await s.refresh()
      api.snapshotDays.mockImplementationOnce(() => Promise.reject(fail(502, 'SNAPSHOT_FAILED')))
      await tid(w, 'se-snap-date').trigger('click')
      await flushPromises()
      expect(tid(w, 'se-snap-calendar').text()).toContain(MESSAGES.SEW_SNAP_CAL_FAILED)
      expect(tids(w, 'se-snap-cal-day').find((d) => d.attributes('data-date') === '2026-11-05').attributes('disabled')).toBeUndefined()
    })
  })

  describe('거르기·상태 글', () => {
    it('전체·태그 거르기와 보이는 개수', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      expect(tid(w, 'se-snap-count').text()).toBe('5장')
      expect(tid(w, 'se-snap-filter-all').attributes('aria-pressed')).toBe('true')
      await tid(w, 'se-snap-filter-tag').trigger('click')
      expect(s.filter).toBe('tag')
      expect(tid(w, 'se-snap-count').text()).toBe('2장')
      expect(tid(w, 'se-snap-filter-tag').attributes('aria-pressed')).toBe('true')
      expect(tids(w, 'se-snap-row')).toHaveLength(2)
    })
    it('받는 중', async () => {
      const { w, s } = await mountPanel()
      const gate = defer()
      api.snapshotDays.mockImplementationOnce(() => gate.promise)
      s.pickEquipment('SEWT_CVD_A01')
      await flushPromises()
      expect(tid(w, 'se-snap-state').text()).toBe(MESSAGES.SEW_SNAP_LOADING)
      gate.resolve({ data: { data: { eqpId: 'SEWT_CVD_A01', ...DAYS } } })
    })
    it('조회 실패는 "목록을 받지 못했습니다" 와 이유, [다시 시도] 로 다시 받는다', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      api.snapshots.mockImplementationOnce(() => Promise.reject(fail(503, 'SNAPSHOT_DOWN')))
      await s.setDate('2026-11-10')
      await flushPromises()
      expect(tid(w, 'se-snap-state').text()).toContain(MESSAGES.SEW_SNAP_LIST_FAILED)
      expect(tid(w, 'se-snap-state').text()).toContain(MESSAGES.SEW_ERR_SNAPSHOT_DOWN)
      await tid(w, 'se-snap-retry').trigger('click')
      await flushPromises()
      expect(s.list.status).toBe('ready')
      expect(tids(w, 'se-snap-row')).toHaveLength(5)
    })
    it('성공인데 0건이면 "스냅샷이 없습니다." — 실패와 다른 글', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      api.snapshots.mockImplementationOnce((eqpId, date) => ok(listOf(eqpId, date, [])))
      await s.setDate('2026-11-10')
      await flushPromises()
      expect(tid(w, 'se-snap-state').text()).toBe(MESSAGES.SEW_SNAP_EMPTY_DAY)
      expect(tid(w, 'se-snap-retry').exists()).toBe(false)
    })
    it('보관 기간 안에 하나도 없으면 "최근 15일 안에 스냅샷이 없습니다."', async () => {
      api.snapshotDays.mockImplementation((eqpId) => ok({ eqpId, ...DAYS, latest: null }))
      const { w } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      expect(tid(w, 'se-snap-state').text()).toBe(MESSAGES.SEW_SNAP_NO_RECENT)
      expect(tid(w, 'se-snap-date').text()).toContain(MESSAGES.SEW_SNAP_DATE_NONE)
    })
    it('태그 거르기에 맞는 줄이 없으면 "이 날에는 태그 스냅샷이 없습니다."', async () => {
      api.snapshots.mockImplementation((eqpId, date) => ok(listOf(eqpId, date, [click(1), click(2)])))
      const { w } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      await tid(w, 'se-snap-filter-tag').trigger('click')
      expect(tid(w, 'se-snap-state').text()).toBe(MESSAGES.SEW_SNAP_NO_TAG)
    })
    it('5만 줄에서 잘렸으면 목록 위에 알린다', async () => {
      api.snapshots.mockImplementation((eqpId, date) => ok(listOf(eqpId, date, ITEMS, { truncated: true })))
      const { w } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      expect(tid(w, 'se-snap-truncated').text()).toBe(t('SEW_SNAP_TRUNCATED', { n: 5 }))
    })
    it('[접기] 는 패널을 접고, [새로 고침] 은 같은 날을 다시 받는다', async () => {
      const { w, s } = await mountPanel({ pick: 'SEWT_CVD_A01' })
      const before = api.snapshots.mock.calls.length
      await tid(w, 'se-snap-refresh').trigger('click')
      await flushPromises()
      expect(api.snapshots.mock.calls.length).toBe(before + 1)
      await tid(w, 'se-snap-collapse').trigger('click')
      expect(s.open).toBe(false)
    })
  })
})
